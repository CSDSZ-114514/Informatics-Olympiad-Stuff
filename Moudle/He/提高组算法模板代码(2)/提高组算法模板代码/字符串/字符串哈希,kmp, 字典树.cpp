//字符串哈希：将字符串映射成p进制的整数，主要用于O(1)的时间复杂度完成字符串匹配
// base: 进制，通常设为131 或13331 
// p[x]:base进制的x次幂, h[x]：前x个元素在base进制下的整数，
//数组定义成 unsigned long long 类型

ULL p[2000005], h[2000005];
int n, base = 131;
 
//初始化p数组，p[x]: base的x次幂的值 
void initP(int len) {
	p[0] = 1;
	for(int i=1; i<=len; i++) { //枚举更新base的幂次数组 
		p[i] = p[i-1]*base;
	}
}
//初始化h数组：h[i]:前i个元素形成字串的base进制整数3 
void initH(string s) {
	for(int i=1; i<=s.size(); i++) { //枚举字符串的所有元素, 从[1, s.size()] 
		h[i] = h[i-1]*base + s[i-1]; //更新h[i],前i-1个元素左移1位，然后加上当前字符 
	}
} 

//获得字符串字串的哈希值，区间第[L, R] 字符形成的子串 
ULL get(int L, int R) {
	return h[R] - h[L-1]*p[R-L+1]; //类似于前缀和，h[右端点]- h[左端点-1]* 左移区间长度位 
}

//kmp算法：字符串匹配算法，在主串s中查找模式串p出现的位置，时间复杂度 O(n+m) 
//先预处理模式串p，构建匹配表next 数组，维护相等真前后缀的最长长度
//然后在进行字符串匹配，当不能匹配时，模式串返回到最优位置

int main() {
	
	//预处理next 数组，ne[i]:前i个字符组成的子串的最长相等真前后缀长度 
	ne[1]=0; //初始化一个元素 
	//i：当前正在处理的模式串第i个字符  j：前i-1个字符子串的最长相等真前后缀长度 
	for(int i=2,j=0; i<=m; i++) { //枚举模式字符串的每一个字符 m:模式字符串长度 
		//如果当前字符 和 前i-1个字符子串的长度的下一个字符不等，则缩小长度 
		while(j && p[i] != p[j+1]) {  //循环处理直到相等或j==0 
			j = ne[j]; //缩小长度 
		}
		if(p[i] == p[j+1]) { //如果当前字符 和 上一个长度j的下一个字符相等 
			j++; //最长长度+1 
		}
		ne[i] = j; //更新next数组 
	}
	
	//主字符串匹配模式字符串
	//i:主字符串的第i个字符  j：前i-1个字符匹配到模式串的位置 
	for(int i=1, j=0; i<=n; i++) {
		//当前字符和匹配长度的下一个字符不相等，缩小匹配长度 
		while(j && s[i] != p[j+1]) { //循环处理到相等或 j==0 
			j = ne[j];
		}
		
		if(s[i] == p[j+1]) { //当前字符和匹配长度的下一个字符相等 
			j++; //匹配长度 + 1 
		}
		if(j == m) { //如果匹配长度等于模式串长度，完成匹配 
			cout<<i-m+1<<endl; //区间[i-m+1, i] 和模式串相同 
		}
	} 

} 

//字典树:快速插入和查询字符串的多叉树结构, 树的每条边对应一个字符，根节点编号0
//其他节点存储路径，可用于字符串查询或前缀查询
//字典树数组t[p][j]:从结点p沿着字符j这条边走到的子节点编号
//计数数组cnt[p]：存储以结点p结尾的单词的插入次数

//将字符串s插入到字典树 
void insert(string s) {
	int p = 0; //从根节点开始插入 
	for(int i=0; i<s.size(); i++) { //一次枚举字符串的每个字符 
		int j = s[i] - 'a';
		if(t[p][j]) { //如果存在字符s[i]这条边 
			p = t[p][j]; //跳到子结点继续 
		} else {
			t[p][j] = ++idx; //如果不存在，创建新的节点 
			p = idx; //跳到子结点 
		}
	}
	cnt[p]++; //最后一个字符在p位置，更新以当前字符结尾的字符串的个数 
} 

//查询字符串是否存在 
int query(string s) {
	int p =0; //从根节点开始查 
	for(int i=0; i<s.size(); i++) {
		int j = s[i]-'a';
		if(t[p][j]) { //如果当前字符存在 
			p = t[p][j]; //跳到子结点查找 
		} else {
			return 0; //如果不存在则返回不存在 
		}
	}
	if(cnt[p] == 0) { //如果所有字符都存在，但没有以p节点结尾的字符串，则没有查到 
		return 0;
	} else {
		return 1;
	}
}
