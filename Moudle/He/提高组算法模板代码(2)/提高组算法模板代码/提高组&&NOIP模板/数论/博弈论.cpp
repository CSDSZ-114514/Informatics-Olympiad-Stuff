//如果一个人没有石子可以移动，他就输了，问先手是否必胜。
//必胜策略：若奇数台阶上的a1^a3^…… ≠ 0 ，则先手必胜，反之，先手必败。

//有向图游戏：在一个有向无环图中，图中只有一个起点，在起点上放一个棋子，
//两个玩家轮流沿着有向边推动棋子，每次走一步，不能走的玩家失败。 
//SG函数：SG(u) = mex(SG(v1),SG(v2)SG(vk)} , vi是u的子结点
//SG定理：n个有向图游戏组成的组合游戏，起点分别是s1,s2……sn
// 当 SG(s1)^SG(s2)^…^SG(sn) ≠0，先手必胜，否则，先手必败

int getSG(int u) {
	//记忆化搜索 
	if(sg[u] != -1) {
		return sg[u];
	} 
	
	//把子结点的SG值插入集合 
	set<int> s;
	for(int v:e[u]) {
		s.insert(getSG(v));
	}
	
	//mex运算求当前节点的sg值并记忆 
	for(int i=0;; i++) {//从0开始枚举 
		if(!s.count(i)) { //当前值i是不被包含在子结点SG集合的最小非负整数 
			return sg[u] = i;
		}
	}
} 
 
