//容斥原理：给定n个集合，求n个集合的并集，等于集合交的交错和（积加偶减）
//方法一：用n位二进制数中1的位置和个数表示集合是否包含，数值范围：1~2^n-1
ll cal() {
	ll res = 0;
	
	for(int i=1; i<(1<<n); i++) { //枚举所有的数 
		ll t=1, sign=-1; // sign用来标识是奇数个集合，还是偶数个集合 
		for(int j=1; j<=n; j++) { //判断n位二进制中第j位是否为1 
			if(i>>(j-1) & 1) { //当前位是1 
				t*=p[j]; //根据题意，更新当前集合交集 
				sign *= -1;
				if(t>m) { //优化，超出范围不判断后面的1 
					break;
				}
			}
		}
		
		//根据奇加偶减处理当前集合交的值 
		res = (res + sign * (m/t * (t + m/t*t)/2)) % mod;
	}	
	return (res%mod+mod)%mod;
} 
