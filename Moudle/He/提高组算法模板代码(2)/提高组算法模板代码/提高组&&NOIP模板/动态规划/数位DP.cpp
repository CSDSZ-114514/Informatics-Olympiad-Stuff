//数位DP：主要用于解决在区间[L, R] 内，求满足某种性质的数的个数。
//处理步骤： 
//1. 初始化：根据题意确定状态数组和状态转移方程，并求出所有状态信息
//2. 根据前缀和思想，将区间[L, R] 转化为[0, R] – [0, L-1] 求解
//3. 将给定的数以十进制的形式进行分解，然后按照一定顺序（通常从高位到低位）
//    逐个处理这些位数，进行分类填数（通常分为两类 0~a[i]-1 和 a[i])。 

//例如：求范围[l,r] 内，数位中包含给定数字x的数的个数
//状态数组：f[i]:前i位中包含数字x的个数
//初始化，求出所有状态信息 
void init() {
	f[1] = 1; //1位数字中只有1个数字含x 
	
	//递推更新从第2位到最高位 
	for(int i=2; i<=18; i++) {
        //更新状态转移方程
		f[i] = f[i-1]*9 + (ll)pow(10, i-1); 
	}
}

//求出[1,n]范围内含x的个数 
ll dp(ll n) {
	//将数字n以十进制形式进行分解 
	int cnt = 0;
	bool flag = false;
	while(n) {
		a[++cnt] = n%10; //保存每一位上的值 
		n/=10;
		if(a[cnt] == x) {
			flag = true;
		}
	}
	
	//从最高位到最低位进行枚举，处理到第i位时，i+1位~cnt位均固定为n的值 
	ll res = 0;
	for(int i=cnt; i>=1; i--) {
		//每一位上的值，分成两部分[0,a[i]-1] 和a[i] 
		
		//枚举[0,a[i]-1]内的每一个值分别处理 
		for(int j=0; j<a[i]; j++) {
			if(j==x) { //当前位上的值等于x 
				res += (ll)pow(10, i-1); 
			} else { //当前位上的值不等于x 
				res += f[i-1];
			}
		}
		
		//处理n本身是否满足条件 
		if(i==1) {
			if(flag) {
				res++;
			}
		}
	}
	
	return res;
}

