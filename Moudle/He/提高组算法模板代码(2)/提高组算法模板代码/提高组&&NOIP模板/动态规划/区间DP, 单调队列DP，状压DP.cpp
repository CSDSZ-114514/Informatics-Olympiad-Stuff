//区间DP：要求大区间的最优解需要先求小区间的最优解，
//然后再通过小区间的最优解合并成大区间

for(int len=2; len<=n; len++) { //枚举区间长度 
	for(int i=1; i+len-1<=n; i++) { //枚举区间起点 
		int j = i+len-1; //区间终点 
		for(int k=i; k<j; k++) { //枚举[i,j]划分成两个区间的中间点k,[i,k]和[k+1,j] 
			f[i][j] = min(f[i][j], f[i][k]+f[k+1][j]+sum[j]-sum[i-1]);
		}
	}
} 

