//单调队列DP：使用双端队列，时间复杂度O(1)的情况下求固定窗口长度的极值
for(int i=1; i<=n; i++) {
	//队尾出队:如果当前值更优 
	while(!q.empty() && a[i] < a[q.back()]) {
		q.pop_back();
	}
	//当前索引入队 
	q.push_back(i);
	
	//队首溢出窗口出队：队首索引<窗口左端点。窗口区间[i-m+1, i] 
	if(q.front() < i-m+1) {
		q.pop_front();
	}
	//输出 
	if(i>=m) {
		cout<<a[q.front()]<<" "; //队首元素是以i为终点，窗口长度为m的极值 
	}
}

