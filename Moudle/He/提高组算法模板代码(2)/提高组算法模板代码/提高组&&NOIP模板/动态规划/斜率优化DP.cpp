//斜率优化DP：把决策与决策之间表示成一个类似斜率 (y1-y2)/(x1-x2) 的式子，
//并用队列维护其有用决策，因此斜率优化又称为队列优化。
//状态转移方程形如：f[i] = min(f[j]+a[j]+a[i]) (0<=j<i),利用单调队列优化
//状态转移方程形如：f[i]=min(f[j]+a[i]*a[j])(0<=j<i),利用斜率优化DP进行优化

//步骤一：写出状态转移方程，并进行转化成 y=kx+b的形式 
//例如：状态转移方程：f[i] = min(f[i], f[j] + t[i] * (c[i]-c[j]) + s*(c[n]-c[j]));
// -> f[i] = f[j] + t[i] * (c[i]-c[j]) + s*(c[n]-c[j])
//把跟j相关的看成变量，方程左边只有变量，方程右边一个含有变量，其他是常量 
//-> f[j]= (t[i]+s) *c[j] + f[i] - t[i] * c[i] -s*c[n] 
//对比 y=kx+b :  y=f[j],  x=c[j], k = t[i]+s   b=f[i] - t[i] * c[i] -s*c[n] 
// 对于 0<=j<=i-1, 共有i-1对坐标点满足方程，每一个方程有一个b
// 要求f[i]最小，则要求截距b最小

//根据单调队列，对于每一个i找到满足条件的保证最小截距的j，处理步骤： 
//1. 若新点 i-1 与队尾点的斜率 < 队尾临点直线的斜率，则队尾出队，删除无用点，维护决策点的下凸壳
//2. 新点i-1入队
//3. 如果斜率是单调递增的：若队头临点直线的斜率<=k, 则队头出队，删除过时点
//   如果斜率不是单调递增：通过二分法找到相邻点直线斜率>k的最小点
//4. 如果斜率单调递增，队头即为j点，若不单调递增，查找到的点为j点，
// 将j点带入转移方程得到f[i]的值 

//根据转化后的方程，返回i点和j点形成直线的斜率 
double slope(int i, int j) {
	return 1.0*(f[i]-f[j])/(sc[i]-sc[j]==0?1e-9:sc[i]-sc[j]);
}

int main() {
	cin>>n>>s;
	for(int i=1; i<=n; i++) {
		int t, c;
		cin>>t>>c;
		t[i] = t[i-1] + t;
		c[i] = c[i-1] + c;
	}
	
	int h=1, t=0; //用数组模拟队列，h：队首  t:队尾
	
	//依次处理每一个点 
	for(int i=1; i<=n; i++) {
		//当前队列元素个数>=2 && i-1对队尾形成的斜率 <=队尾相邻点形成的斜率 
		while(h<t && slope(i-1, q[t]) <= slope(q[t], q[t-1])) {
			t--; //队尾出队 
		}
		q[++t] = i-1; //新点入队
		
		//当斜率单调递增是，如果队首相邻斜率 <= k,则队首出队 
		while(h<t && slope(q[h+1], q[h]) <= t[i]+s) {
			h++; //队首出队 
		}
		int j = q[h]; //队首即为j点 
		f[i] = f[j] + t[i] * (c[i]-c[j]) + s*(c[n]-c[j]); //更新f[i] 
	}
	
	cout<<f[n];
	
	
	return 0;
} 
