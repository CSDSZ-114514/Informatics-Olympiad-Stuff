//Manacher 算法：用于在线性时间复杂度O(n)内查找字符串的最长回文子串
//预处理：如果需要包含偶数回文子串，在字符之间和两端添加特殊字符#, 处理后，可以都变成奇回文串
// 维护回文半径d[i]: 以i为中心的最长回文串长度的一半（包含自己）
//维护加速盒子[L,R]: 维护右端点最靠右的最长回文串的左右端点
// 通过判断i点是否在加速盒子，盒内d[i]利用对称点转移，盒外暴力

int main() {
	cin>>a;
	
	s[0] = '$', s[++n] = '#'; //原字符串中的字符之间用#分隔，保证中心点在字符上 
	for(int i=0; i<a.size(); i++) {
		s[++n] = a[i];
		s[++n] = '#';
	}

	d[1] = 1; 
	for(int i=2, l, r=1; i<=n; i++) { // i: 枚举每个字符  l,r：维护加速盒子 
		if(i<=r) { //在加速盒子内，重复利用已求的值  
			d[i] = min(d[r-i+l], r-i+1); //加速盒子内，i的对称点 r-i+l 
		}
		while(s[i+d[i]] == s[i-d[i]]) { //超出盒子暴力枚举 
			d[i]++; 
		}
		if(i+d[i]-1 > r) { //如果右区间超过r，更新盒子区间 
			l = i-d[i]+1;
			r = i+d[i]-1;
		}
		
		ans = max(ans, d[i]-1); //d[i]-1 是回文串得长度 
	} 

	cout<<ans; 

	return 0;
} 

