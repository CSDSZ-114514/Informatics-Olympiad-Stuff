//欧拉路：从一个点出发，可以不重复的走完所有边，则图具有欧拉路，如果能回到起点，
//则具有欧拉回路，具有欧拉回路的图是欧拉图
//无向图：有0个奇数点具有欧拉回路，有2个奇数点（分别是起点和终点）具有欧拉路
//有向图：所有点的入度和出度相等，则具有欧拉路。
//        存在两个点出度比入度大1（起点），入度比出度大1（终点），其他点入度出度相同，则具有欧拉路

//欧拉路径的输出通过深搜遍历，栈存储

//用vector存储图时，数组del[u]保存节点u遍历到第几个节点 
void dfs(int u) {
	for(int i = del[u]; i<e[u].size(); i=del[u]) { // 从上次走完的边开始 
		del[u] = i+1;
		dfs(e[u][i]);
	}
	s.push(u); //深搜返回时入栈 
} 

