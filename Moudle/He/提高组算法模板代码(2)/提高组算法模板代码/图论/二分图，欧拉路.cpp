//二分图：将顶点分成两个互不相交的子集，如果每一条边的两个顶点属于不同的集合
//则这个图时二分图，可以用染色法判定

//深搜方式处理，对结点u染色
void dfs(int u) {
	for(int v:g[u]) { //依次遍历每一个出边 
		if(f[v] == -1) { //如果没访问 
			f[v] = f[u]^1;  //更新状态为0->1, 1->0 
			dfs(v);
		} else if(f[v] != f[u]^1) { //如果访问过，但染色冲突，则不是二分图 
			cout<<"Impossible"; //出现冲突，退出 
			exit(0);
		}	
	}
} 


