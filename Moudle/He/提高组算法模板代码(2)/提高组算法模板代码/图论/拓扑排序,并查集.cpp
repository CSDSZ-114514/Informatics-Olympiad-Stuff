//并查集，用于集合处理，支持集合合并和查询
//集合处理，主要是对集合根的处理 

//并查集查到x所在集合得根节点 
int find(int x) {
	if(x == fa[x]) {
		return x;
	} else {
		return fa[x] = find(fa[x]);
	}
}
//x,y所在集合进行合并 
void unionset(int x, int y) {
	fa[find(x)] = find(y);
} 

