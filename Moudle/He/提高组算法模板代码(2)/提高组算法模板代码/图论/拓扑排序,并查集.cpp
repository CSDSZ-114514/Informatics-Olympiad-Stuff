//拓扑排序：有向图中查找序列，满足对所有的有向边 x->y，序列中x都在y前面
//计算所有点的入度，入度为0的节点队列，依次取出队首元素u，当前元素是拓扑序列的元素，
//依次处理队首元素u的所有出边v，v的入度减1，当入度为0时，v入队
//如果出队的元素<n, 则有向图有环。

void toposort() {
	for(int i=1; i<=n; i++) {
		if(d[i] == 0) { //所有入队为0的节点全部入队 
			q.push(i);
		}
	}

	while(!q.empty()) {
		int u = q.front(); //依次取出队首元素 
		q.pop();
		
		cout<<u<<" "; //当前元素是拓扑序列一部分 
		for(int v:e[u]) {
			d[v]--; //出边节点入队减1 
			if(d[v] == 0){ //当入度为0时，节点入队 
				q.push(v);
			}
		}
	} 
} 


