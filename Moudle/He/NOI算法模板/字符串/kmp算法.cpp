//kmp算法：用于在主字符串s中查找模式字符串p出现的位置，核心思想是通过预处理模式字符串p，
//构建next数组(相等真前后缀的最长长度），避免在匹配过程中不必要的回溯，时间复杂度O(n+m)
//字符串的最短循环节长度 = 字符串长度 - 最长相等前后缀的长度 = n-ne[n]

int main() {

	//初始化模式字符串next数组，保存最长相等真前后缀的长度 
	ne[1]=0;
	for(int i=2,j=0; i<=m; i++) { //i:枚举模式串的每个字符，j：前i-1子串的最长长度 
		while(j && p[i] != p[j+1]) { //如果当前字符不匹配 j的下一个字符 
			j = ne[j]; //缩小匹配长度 
		}
		if(p[i] == p[j+1]) {//如果当前字符可以匹配 j的下一个字符 
			j++; //匹配长度+1 
		}
		ne[i] = j; //更新i的next值 
	}
	
	//枚举主字符串s的每一个字符，判断和模式字符串p的匹配长度 
	for(int i=1, j=0; i<=n; i++) { //i：枚举s的每个字符， j: i-1个字符匹配的长度 
		while(j && s[i] != p[j+1]) {//如果当前字符i不匹配j的下一个字符
			j = ne[j]; //缩小匹配长度 
		}
		if(s[i] == p[j+1]) { //如果当前字符i匹配j的下一个字符 
			j++; //匹配长度+1 
		}
		if(j == m) { //如果匹配长度等于模式字符串的长度，完成一次匹配，i是匹配的终点 
			cout<<i-m+1<<endl;
		}
	}
	

	return 0;
}
