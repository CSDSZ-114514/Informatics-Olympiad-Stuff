//字典树：能够快速查询和插入的多叉树结构，主要用于字符串前缀查找处理 
//树上的每条边对应一个字符，根节点编号为0
//其他节点标识路径，代表从根到该节点的路径所对应的字符串
//字典树存储：数组 t[N][Z]: 第一个维度节点编号，第二个维度字符，值为出边对应的编号

//字符串插入：从根节点0开始，枚举字符串的每一个字符，如果有子结点，则指向子结点
//如果没有子结点，则先创建子结点，在指向子结点 
void insert(string s) {
	int p = 0; //设定根节点编号0 
	for(int i=0; i<s.size(); i++) { //枚举字符串的每一个字符 
		int j = s[i]-'a'; //获取当前字符 
		if(t[p][j]) { //如果有子结点 
			p = t[p][j]; //指向子结点 
		} else {
			t[p][j] = ++idx; //创建新节点 
			p = idx; //指向子结点 
		}
		cnt[p]++; //保存前缀字符串出现的次数 
	}
}

//字符串查询：从根节点0开始查询字符串，枚举字符串的每一个字符，如果存在子结点
//则指向子结点，如果不存在，查找失败 
int query(string s) {
	int p =0;//设置根节点 
	for(int i=0; i<s.size(); i++) { //枚举字符串的每一个字符 
		int j = s[i]-'a';
		if(t[p][j]) { //如果存在子结点 
			p = t[p][j]; //指向子结点 
		} else {
			return 0; //如果不存在，查找失败 
		}
	}
	return cnt[p]; //返回字符串s出现的次数 
} 
